export default function historyStrings(lang) {
  const o = L[lang] || {}
  return { ...EN, ...o, ranges: { ...EN.ranges, ...(o.ranges || {}) }, intervals: { ...EN.intervals, ...(o.intervals || {}) } }
}

/** fill('{n} rows', { n: 5 }) */
export function fill(s, vars) {
  return String(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''))
}
