const LANGS = ['en', 'zh', 'ja', 'ko', 'fr']

export default function statsStrings(lang) {
  const i = Math.max(0, LANGS.indexOf(lang))
  const labels = Object.fromEntries(Object.entries(LABELS).map(([k, v]) => [k, v[i]]))
  return { ...EN, ...(L[lang] || {}), labels }
}
