const CUR_CODES = ['GBP', 'USD', 'EUR', 'CNY', 'JPY', 'KRW', 'OTHER']
const QUOTE = { GBP: '$', USD: '€', EUR: '$', CNY: '$', JPY: '$', KRW: '$' }
function currencies(names, short, price, qty, otherPrice, otherQty) {
  return Object.fromEntries(CUR_CODES.map((c) => [c, c === 'OTHER'
    ? { name: names.OTHER, price: otherPrice, qty: otherQty }
    : { name: names[c], price: price(short[c], QUOTE[c]), qty: qty(short[c]) }]))
}

