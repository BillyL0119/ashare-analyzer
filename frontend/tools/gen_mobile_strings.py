HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("l10n", os.path.join(HERE, "..", "..", "ios", "tools", "l10n_catalog.py"))
l10n = importlib.util.module_from_spec(spec); spec.loader.exec_module(l10n)

# key (Chinese) -> (en, ja, ko, fr); only strings that exist on the web but not in the iOS app
