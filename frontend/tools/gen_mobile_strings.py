#!/usr/bin/env python3
"""Builds src/mobile/strings.js from the iOS translation table (single source of truth) plus a few
web-only strings, and fails if a t('...') key used by the mobile UI has no translation.

    python3 frontend/tools/gen_mobile_strings.py
"""
